function mountName(id: string): string {
  return CHOCOBO_COLORS.find((c) => c.id === id)?.label ?? "Yellow";
}

function placeLabel(place: number | null | undefined): string {
  if (!place) return "DNF";
  const suffix = place === 1 ? "ST" : place === 2 ? "ND" : place === 3 ? "RD" : "TH";
  return `${place}${suffix}`;
}

